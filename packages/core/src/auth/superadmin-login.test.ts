import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => ({ rateLimit: vi.fn() }));
vi.mock('../rate-limit', () => ({ rateLimit: mocks.rateLimit }));

import { hashSuperadminPassword } from './superadmin-password';
import { verifySuperadminLogin } from './superadmin-login';

const PASSWORD = 'Correct-Horse-9!';
let hash = '';
const base = { ip: '203.0.113.9' };

beforeAll(async () => {
  hash = await hashSuperadminPassword(PASSWORD);
});

beforeEach(() => {
  mocks.rateLimit.mockResolvedValue({ allowed: true });
  vi.stubEnv('SUPERADMIN_USER_ID', 'root-admin');
  vi.stubEnv('SUPERADMIN_EMAIL', 'root@example.test');
  vi.stubEnv('SUPERADMIN_PASSWORD_HASH', hash);
});

afterEach(() => {
  vi.unstubAllEnvs();
  vi.clearAllMocks();
});

describe('verifySuperadminLogin', () => {
  it('accepts the configured id with the right password', async () => {
    expect(await verifySuperadminLogin({ ...base, identifier: 'ROOT-ADMIN', password: PASSWORD })).toEqual({ ok: true, userId: 'root-admin' });
  });

  it('honours caseSensitive and identity options', async () => {
    expect(await verifySuperadminLogin({ ...base, identifier: 'ROOT-ADMIN', password: PASSWORD, caseSensitive: true })).toMatchObject({ ok: false, reason: 'id_mismatch' });
    expect(await verifySuperadminLogin({ ...base, identifier: 'root@example.test', password: PASSWORD })).toMatchObject({ ok: false });
    expect(await verifySuperadminLogin({ ...base, identifier: 'root@example.test', password: PASSWORD, identity: 'any' })).toMatchObject({ ok: true });
  });

  it('rejects a wrong password', async () => {
    expect(await verifySuperadminLogin({ ...base, identifier: 'root-admin', password: 'nope-nope-nope' })).toEqual({ ok: false, reason: 'invalid_password' });
  });

  it('is rate limited per ip and per identifier', async () => {
    mocks.rateLimit.mockResolvedValueOnce({ allowed: true }).mockResolvedValueOnce({ allowed: false });
    expect(await verifySuperadminLogin({ ...base, identifier: 'root-admin', password: PASSWORD })).toEqual({ ok: false, reason: 'rate_limited' });
    expect(mocks.rateLimit).toHaveBeenCalledWith(expect.stringContaining('_ip:'), 5, 15 * 60 * 1000);
    expect(mocks.rateLimit).toHaveBeenCalledWith(expect.stringContaining('_user:'), 5, 15 * 60 * 1000);
  });

  it('ignores a plaintext SUPERADMIN_PASSWORD in every environment', async () => {
    vi.stubEnv('SUPERADMIN_PASSWORD_HASH', '');
    vi.stubEnv('SUPERADMIN_PASSWORD', 'plain-password-123');
    vi.stubEnv('NODE_ENV', 'development');
    expect(await verifySuperadminLogin({ ...base, identifier: 'root-admin', password: 'plain-password-123' })).toEqual({ ok: false, reason: 'not_configured' });
  });

  it('falls through without hashing or rate limiting when the id does not match', async () => {
    const result = await verifySuperadminLogin({ ...base, identifier: 'someone@else.test', password: PASSWORD, identity: 'any', fallThrough: true });
    expect(result).toEqual({ ok: false, reason: 'id_mismatch' });
    expect(mocks.rateLimit).not.toHaveBeenCalled();
  });

  it('accepts hashes generated by scripts/hash-superadmin-password.mjs', async () => {
    const script = resolve(__dirname, '../../../../scripts/hash-superadmin-password.mjs');
    const scripted = execFileSync(process.execPath, [script], { env: { ...process.env, SUPERADMIN_NEW_PASSWORD: PASSWORD } }).toString().trim();
    vi.stubEnv('SUPERADMIN_PASSWORD_HASH', scripted);
    expect(await verifySuperadminLogin({ ...base, identifier: 'root-admin', password: PASSWORD })).toMatchObject({ ok: true });
  });
});

describe('plaintext superadmin password', () => {
  it('is never read by application source', () => {
    const root = resolve(__dirname, '../../../..');
    const offenders: string[] = [];
    const walk = (dir: string) => {
      for (const name of readdirSync(dir)) {
        if (name === 'node_modules' || name === '.next' || name === 'dist') continue;
        const path = join(dir, name);
        if (statSync(path).isDirectory()) walk(path);
        else if (/\.(ts|tsx|mjs|js)$/.test(name) && !name.endsWith('.test.ts') && /SUPERADMIN_PASSWORD(?!_HASH)/.test(readFileSync(path, 'utf8'))) {
          offenders.push(path.replace(root, ''));
        }
      }
    };
    for (const top of ['apps', 'packages']) walk(join(root, top));
    expect(offenders).toEqual([]);
  });
});
